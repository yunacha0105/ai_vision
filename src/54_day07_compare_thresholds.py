
# ==================================================
# ① 필요한 라이브러리 불러오기
#    → Path   : 입력 및 출력 파일 경로 관리
#    → NumPy  : Percentile 계산
#    → Pandas : CSV 읽기 및 비교표 저장
# ==================================================
from pathlib import Path

import numpy as np
import pandas as pd


# ==================================================
# ② 입력 및 출력 파일 경로 설정
#    → INPUT_CSV  : 53번에서 계산한 정상 Score
#    → OUTPUT_CSV : Threshold 후보 비교 결과
# ==================================================
INPUT_CSV = Path(
    "reports/day07_validation_scores.csv"
)

OUTPUT_CSV = Path(
    "reports/day07_threshold_compare.csv"
)


# ==================================================
# ③ 정상 Validation Score 불러오기
#    → 53번에서 저장한 CSV 파일 읽기
#    → anomaly_score 열의 숫자만 추출
# ==================================================

# ----------------------------------------------
# ③-1. CSV 파일 읽기
# ----------------------------------------------
df = pd.read_csv(
    INPUT_CSV
)

# ----------------------------------------------
# ③-2. Anomaly Score만 NumPy 배열로 변환
#       → 정상 이미지 42장의 점수
# ----------------------------------------------
scores = df[
    "anomaly_score"
].to_numpy()


# ==================================================
# ④ Threshold 후보 계산 및 비교
#    → 90 / 95 / 99 Percentile 계산
#    → 기준값보다 점수가 높은 정상 이미지 수 확인
#
#    Threshold가 낮을수록
#    정상 이미지를 이상으로 판단할 가능성이 커짐
# ==================================================

# 후보별 계산 결과를 저장할 리스트
candidates = []


# ----------------------------------------------
# ④-1. Percentile 후보를 하나씩 계산
# ----------------------------------------------
for percentile in [
    90,
    95,
    99,
]:

    # ------------------------------------------
    # ④-2. Percentile에 해당하는 Threshold 계산
    #
    #       90 → 정상 Score의 90백분위수
    #       95 → 정상 Score의 95백분위수
    #       99 → 정상 Score의 99백분위수
    # ------------------------------------------
    threshold = float(
        np.percentile(
            scores,
            percentile,
        )
    )

    # ------------------------------------------
    # ④-3. Threshold를 초과하는 정상 이미지 수
    #
    #       정상 이미지인데 Threshold를 넘으면
    #       이후 판정 규칙에서는 Anomaly가 됨
    # ------------------------------------------
    normal_over = int(
        (
            scores
            > threshold
        ).sum()
    )

    # ------------------------------------------
    # ④-4. 후보별 계산 결과 기록
    #       → Percentile / Threshold / 초과 개수
    # ------------------------------------------
    candidates.append(
        {
            "percentile": percentile,
            "threshold": round(
                threshold,
                6,
            ),
            "validation_normal_over_threshold": normal_over,
        }
    )


# ==================================================
# ⑤ Threshold 후보를 비교표로 만들기
#    → 리스트에 저장된 세 가지 후보를
#      Pandas DataFrame 형태로 변환
# ==================================================
result = pd.DataFrame(
    candidates
)


# ==================================================
# ⑥ Threshold 비교 결과를 CSV 파일로 저장
#    → 이후 55번에서 기준값을 선택할 때 활용
# ==================================================

# ----------------------------------------------
# ⑥-1. 저장 폴더 생성
# ----------------------------------------------
OUTPUT_CSV.parent.mkdir(
    parents=True,
    exist_ok=True,
)

# ----------------------------------------------
# ⑥-2. 비교 결과 CSV 저장
# ----------------------------------------------
result.to_csv(
    OUTPUT_CSV,
    index=False,
    encoding="utf-8-sig",
)


# ==================================================
# ⑦ 실행 결과 확인
#    → 정상 이미지 개수 및 Score 통계 출력
#    → 90 / 95 / 99 Percentile 비교 결과 출력
#    → CSV 파일 저장 위치 확인
# ==================================================

# ----------------------------------------------
# ⑦-1. 결과 제목 출력
# ----------------------------------------------
print("=" * 70)
print("Validation Score Summary")
print("=" * 70)


# ----------------------------------------------
# ⑦-2. 정상 이미지 개수 출력
# ----------------------------------------------
print(
    "Count:",
    len(scores),
)


# ----------------------------------------------
# ⑦-3. 가장 낮은 Anomaly Score 출력
# ----------------------------------------------
print(
    "Min  :",
    round(
        float(scores.min()),
        6,
    ),
)


# ----------------------------------------------
# ⑦-4. 평균 Anomaly Score 출력
# ----------------------------------------------
print(
    "Mean :",
    round(
        float(scores.mean()),
        6,
    ),
)


# ----------------------------------------------
# ⑦-5. 가장 높은 Anomaly Score 출력
# ----------------------------------------------
print(
    "Max  :",
    round(
        float(scores.max()),
        6,
    ),
)

print()


# ----------------------------------------------
# ⑦-6. Threshold 후보 비교표 출력
# ----------------------------------------------
print(
    result.to_string(
        index=False
    )
)

print()


# ----------------------------------------------
# ⑦-7. 결과 CSV 저장 경로 출력
# ----------------------------------------------
print(
    "Saved:",
    OUTPUT_CSV,
)