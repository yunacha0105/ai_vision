
# ==================================================
# ① 필요한 라이브러리와 공통 함수 불러오기
#
#    → Path : 파일과 폴더 경로 관리
#
#    day08_cutpaste_core에서 다음 함수 사용
#    → generate_synthetic_set()
#
#    이 함수는 다음 작업을 수행합니다.
#    → 실제 결함 Patch 추출
#    → 정상 이미지에 결함 합성
#    → 합성 이미지 여러 장 생성
#    → 합성 정보 Metadata CSV 저장
# ==================================================
from pathlib import Path

from day08_cutpaste_core import (
    generate_synthetic_set,
)


# ==================================================
# ② 입력 / 출력 경로 설정
#
#    앞의 63번에서 준비한 실습 데이터를 사용합니다.
#
#    입력:
#    → 정상 병 이미지 10장
#    → 작은 파손 원본 이미지 2장
#    → 해당 Ground Truth Mask 2장
#
#    출력:
#    → Synthetic Defect 이미지 20장
#    → 합성 과정 Metadata CSV
# ==================================================

# ----------------------------------------------
# ②-1. 합성에 사용할 정상 병 이미지 폴더
#
#       정상 이미지 10장이 준비되어 있습니다.
#
#       이 정상 이미지 위에
#       실제 파손 결함을 붙입니다.
# ----------------------------------------------
NORMAL_DIR = Path(
    "samples/day08/cutpaste/normal"
)


# ----------------------------------------------
# ②-2. 작은 파손 원본 데이터 폴더
#
#       내부에는 두 폴더가 있습니다.
#
#       images/
#       → 실제 작은 파손 이미지 2장
#
#       masks/
#       → 각 파손 위치의 Ground Truth Mask 2장
# ----------------------------------------------
DEFECT_ROOT = Path(
    "samples/day08/cutpaste/defect_source/broken_small"
)


# ----------------------------------------------
# ②-3. 합성 불량 이미지 저장 폴더
#
#       synthetic_000.png
#       synthetic_001.png
#       ...
#       synthetic_019.png
# ----------------------------------------------
OUTPUT_DIR = Path(
    "outputs/day08/cutpaste/generated"
)


# ----------------------------------------------
# ②-4. 합성 정보 Metadata CSV 저장 경로
#
#       각 합성 이미지에 대해 다음 정보 기록
#       → 사용한 정상 이미지
#       → 사용한 불량 원본
#       → 결함 위치
#       → 결함 크기·회전 각도·배율
# ----------------------------------------------
METADATA_PATH = Path(
    "reports/day08_defect_metadata.csv"
)


# ==================================================
# ③ Cut-Paste 합성 불량 이미지 20장 생성
#
#    generate_synthetic_set()을 호출합니다.
#
#    함수 내부 처리:
#    1) 정상 이미지 1장 선택
#    2) 작은 파손 이미지와 Mask 선택
#    3) Mask를 이용하여 결함 Patch 추출
#    4) 결함 크기와 회전 각도 변경
#    5) 정상 병 이미지에 결함 붙이기
#    6) Synthetic Defect 이미지 저장
#    7) Metadata 기록
#
#    위 과정을 count=20만큼 반복합니다.
#
#    참고:
#    정상 이미지와 불량 원본은 매번
#    무작위로 선택하므로 같은 원본이
#    여러 번 사용될 수 있습니다.
# ==================================================
rows = generate_synthetic_set(

    # ------------------------------------------
    # ③-1. 합성 바탕이 되는 정상 이미지 폴더
    # ------------------------------------------
    normal_dir=NORMAL_DIR,

    # ------------------------------------------
    # ③-2. 실제 작은 파손 이미지 폴더
    #
    #       DEFECT_ROOT / "images"
    # ------------------------------------------
    defect_image_dir=(
        DEFECT_ROOT / "images"
    ),

    # ------------------------------------------
    # ③-3. 실제 결함 위치 Mask 폴더
    #
    #       DEFECT_ROOT / "masks"
    # ------------------------------------------
    defect_mask_dir=(
        DEFECT_ROOT / "masks"
    ),

    # ------------------------------------------
    # ③-4. 합성 이미지 저장 폴더
    # ------------------------------------------
    output_dir=OUTPUT_DIR,

    # ------------------------------------------
    # ③-5. Metadata CSV 저장 경로
    # ------------------------------------------
    metadata_path=METADATA_PATH,

    # ------------------------------------------
    # ③-6. 합성할 결함 종류
    #
    #       이번 본 실습은 broken_small 사용
    # ------------------------------------------
    defect_type="broken_small",

    # ------------------------------------------
    # ③-7. 생성할 합성 불량 이미지 수
    #
    #       총 20장 생성
    # ------------------------------------------
    count=20,

    # ------------------------------------------
    # ③-8. 무작위 선택 Seed 고정
    #
    #       동일한 입력 데이터와 설정에서
    #       합성 결과를 재현하기 위한 값
    # ------------------------------------------
    seed=42,

    # ------------------------------------------
    # ③-9. 결함 Patch 크기 변경 범위
    #
    #       0.7 → 원래 크기의 70%
    #       1.2 → 원래 크기의 120%
    #
    #       범위 안에서 무작위로 선택
    # ------------------------------------------
    scale_range=(0.7, 1.2),

    # ------------------------------------------
    # ③-10. 결함 Patch 회전 각도 범위
    #
    #        -15도 ~ +15도
    #
    #        범위 안에서 무작위로 선택
    # ------------------------------------------
    angle_range=(-15.0, 15.0),
)


# ==================================================
# ④ 실행 결과 확인
#
#    → 합성한 결함 종류 출력
#    → 실제 생성한 이미지 수 출력
#    → 합성 이미지 저장 경로 출력
#    → Metadata CSV 저장 경로 출력
#
#    rows에는 생성한 이미지 20장의
#    Metadata 정보가 들어 있습니다.
# ==================================================

# ----------------------------------------------
# ④-1. 실행 결과 제목 출력
# ----------------------------------------------
print("=" * 70)
print("DAY08 CUT-PASTE DEFECT GENERATION")
print("=" * 70)


# ----------------------------------------------
# ④-2. 합성한 결함 종류 출력
# ----------------------------------------------
print(
    "Defect Type      : broken_small"
)


# ----------------------------------------------
# ④-3. 생성한 이미지 수 출력
#
#       len(rows)
#       → 생성 결과 Metadata 개수
#       → 정상 완료 시 20
# ----------------------------------------------
print(
    "Generated Images :",
    len(rows)
)


# ----------------------------------------------
# ④-4. 합성 이미지 저장 위치 출력
# ----------------------------------------------
print(
    "Output           :",
    OUTPUT_DIR
)


# ----------------------------------------------
# ④-5. Metadata CSV 저장 위치 출력
# ----------------------------------------------
print(
    "Metadata         :",
    METADATA_PATH
)