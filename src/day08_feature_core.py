
# ==================================================
# ① 필요한 라이브러리 불러오기
#    → NumPy       : Feature 계산 및 배열 처리
#    → PyTorch     : 사전학습된 ResNet18 실행
#    → F           : Feature Vector 정규화
#    → Pillow      : 이미지 읽기 및 RGB 변환
#    → transforms  : ResNet18 입력 이미지 전처리
# ==================================================
import numpy as np
import torch
import torch.nn.functional as F

from PIL import Image

from torchvision import transforms

from torchvision.models import (
    resnet18,
    ResNet18_Weights,
)


# ==================================================
# ② 실행 장치 설정
#    → CUDA 사용 가능 : GPU 사용
#    → CUDA 사용 불가 : CPU 사용
#
#    GPU가 없어도 실행할 수 있습니다.
# ==================================================
DEVICE = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)


# ==================================================
# ③ ResNet18 입력 이미지 전처리 설정
#    → 병 이미지 크기를 224 × 224로 변경
#    → 이미지를 PyTorch Tensor로 변환
#    → ImageNet 기준 평균과 표준편차로 정규화
#
#    왜 전처리할까요?
#    → 사전학습된 ResNet18이 사용할 수 있는
#      일정한 입력 형태로 이미지를 맞추기 위해서입니다.
# ==================================================
PREPROCESS = transforms.Compose(
    [
        # ------------------------------------------
        # ③-1. 이미지 크기를 224 × 224로 변경
        # ------------------------------------------
        transforms.Resize(
            (224, 224)
        ),

        # ------------------------------------------
        # ③-2. 이미지를 Tensor로 변환
        #       → RGB 픽셀값을 0~1 범위로 변환
        # ------------------------------------------
        transforms.ToTensor(),

        # ------------------------------------------
        # ③-3. ImageNet 기준으로 정규화
        #       → RGB 채널별 평균과 표준편차 사용
        # ------------------------------------------
        transforms.Normalize(
            mean=[0.485, 0.456, 0.406],
            std=[0.229, 0.224, 0.225],
        ),
    ]
)


# ==================================================
# ④ Feature 추출용 ResNet18 모델 생성
#
#    함수: create_feature_model()
#
#    → ImageNet 사전학습 ResNet18 불러오기
#    → 마지막 분류층(fc) 제외
#    → 이미지 특징 추출용 모델로 사용
#
#    이번에는 새로운 모델을 학습하지 않습니다.
# ==================================================
def create_feature_model():

    # ----------------------------------------------
    # ④-1. 사전학습된 ResNet18 불러오기
    # ----------------------------------------------
    model = resnet18(
        weights=ResNet18_Weights.DEFAULT
    )

    # ----------------------------------------------
    # ④-2. 마지막 분류층을 제외하고 구성
    #
    #       ResNet18 특징 추출부
    #       → Average Pooling까지 사용
    #       → 마지막 fc 분류층은 사용하지 않음
    #
    #       출력 특징 수: 512개
    # ----------------------------------------------
    feature_model = torch.nn.Sequential(
        *list(model.children())[:-1]
    )

    # ----------------------------------------------
    # ④-3. 평가 모드로 설정
    #       → BatchNorm 등 평가 방식 적용
    # ----------------------------------------------
    feature_model.eval()

    # ----------------------------------------------
    # ④-4. GPU 또는 CPU로 모델 이동
    # ----------------------------------------------
    feature_model.to(
        DEVICE
    )

    # ----------------------------------------------
    # ④-5. 특징 추출 모델 반환
    # ----------------------------------------------
    return feature_model


# ==================================================
# ⑤ 병 이미지에서 Feature Vector 추출
#
#    함수: extract_feature()
#
#    → 이미지 읽기
#    → 전처리
#    → ResNet18 실행
#    → 512차원 Feature Vector 생성
#    → L2 정규화
#
#    @torch.no_grad()
#    → 특징 추출 중 기울기를 계산하지 않음
#    → 모델 학습은 수행하지 않음
# ==================================================
@torch.no_grad()
def extract_feature(
    model,
    image_path
):

    # ----------------------------------------------
    # ⑤-1. 병 이미지 읽기
    #       → RGB 3채널 이미지로 변환
    # ----------------------------------------------
    image = Image.open(
        image_path
    ).convert("RGB")

    # ----------------------------------------------
    # ⑤-2. 이미지 전처리
    #
    #       PREPROCESS(image)
    #       → 이미지 크기 및 픽셀값 정규화
    #
    #       unsqueeze(0)
    #       → Batch 차원 추가
    #
    #       to(DEVICE)
    #       → GPU 또는 CPU로 이동
    # ----------------------------------------------
    tensor = (
        PREPROCESS(image)
        .unsqueeze(0)
        .to(DEVICE)
    )

    # ----------------------------------------------
    # ⑤-3. ResNet18로 특징 추출
    #
    #       Feature Model 출력
    #       → (1, 512, 1, 1)
    #
    #       flatten(1)
    #       → (1, 512)
    #
    #       이미지 1장당 특징값 512개 생성
    # ----------------------------------------------
    feature = model(
        tensor
    ).flatten(1)

    # ----------------------------------------------
    # ⑤-4. Feature Vector L2 정규화
    #
    #       벡터의 길이를 1로 맞춤
    #
    #       이후 코사인 유사도를
    #       내적으로 계산할 수 있도록 준비
    # ----------------------------------------------
    feature = F.normalize(
        feature,
        p=2,
        dim=1,
    )

    # ----------------------------------------------
    # ⑤-5. Feature Vector 반환
    #
    #       feature[0] : 첫 번째 이미지 특징
    #       cpu()      : CPU로 이동
    #       numpy()    : NumPy 배열로 변환
    #
    #       최종 형태: (512,)
    # ----------------------------------------------
    return (
        feature[0]
        .cpu()
        .numpy()
    )


# ==================================================
# ⑥ 두 이미지 특징의 Cosine Similarity 계산
#
#    함수: cosine_similarity()
#
#    → Feature Vector 두 개를 비교
#    → 얼마나 비슷한 방향인지 숫자로 계산
#
#    이 함수의 입력은 L2 정규화된 Vector입니다.
#
#    유사도 높음 → 특징이 서로 비슷함
#    유사도 낮음 → 특징 차이가 상대적으로 큼
# ==================================================
def cosine_similarity(
    feature_a,
    feature_b
):

    # ----------------------------------------------
    # ⑥-1. 정규화된 두 Feature Vector의 내적 계산
    #
    #       np.dot()으로 계산
    #
    #       두 벡터의 길이가 1이므로
    #       내적값이 코사인 유사도에 해당
    # ----------------------------------------------
    return float(
        np.dot(
            feature_a,
            feature_b
        )
    )


# ==================================================
# ⑦ 여러 이미지의 대표 특징 Prototype 생성
#
#    함수: build_prototype()
#
#    → Support 이미지들의 Feature Vector를 받음
#    → 여러 Vector의 평균 계산
#    → 평균 Vector의 길이를 1로 정규화
#    → 대표 특징(Prototype) 반환
#
#    Few-shot에서는 정상 Support와 불량 Support로
#    각각 별도의 Prototype을 생성합니다.
# ==================================================
def build_prototype(
    features
):

    # ----------------------------------------------
    # ⑦-1. 여러 이미지의 특징을 하나로 묶기
    #
    #       예: 정상 Support 5장의 특징
    #       → (5, 512)
    # ----------------------------------------------
    stacked = np.stack(
        features
    )

    # ----------------------------------------------
    # ⑦-2. 특징별 평균값 계산
    #
    #       5장의 특징을 평균
    #       → (512,)
    #
    #       이 평균 특징이 Prototype의 기본 형태
    # ----------------------------------------------
    prototype = stacked.mean(
        axis=0
    )

    # ----------------------------------------------
    # ⑦-3. 평균 Feature Vector의 길이 계산
    #       → L2 Norm 계산
    # ----------------------------------------------
    norm = np.linalg.norm(
        prototype
    )

    # ----------------------------------------------
    # ⑦-4. 벡터 길이가 0이면 오류 발생
    #
    #       길이가 0이면 정규화할 수 없음
    # ----------------------------------------------
    if norm == 0:

        raise RuntimeError(
            "Prototype norm이 0입니다."
        )

    # ----------------------------------------------
    # ⑦-5. Prototype을 정규화하여 반환
    #
    #       최종 형태: (512,)
    #
    #       Query와 Cosine Similarity 비교에 사용
    # ----------------------------------------------
    return (
        prototype / norm
    )


