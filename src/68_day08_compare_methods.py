
# ==================================================
# ① 필요한 라이브러리 불러오기
#
#    → csv    : 성능 비교 결과를 CSV로 저장
#    → Path   : 입력 및 출력 파일 경로 관리
#    → pandas: One-shot / Few-shot 결과 분석
#
#    이번 코드는 이미 저장된 검사 결과를 비교합니다.
#    ResNet18 모델을 다시 실행하지 않습니다.
# ==================================================
import csv
from pathlib import Path

import pandas as pd


# ==================================================
# ② 입력 / 출력 파일 경로 설정
#
#    → 65번에서 저장한 One-shot 결과
#    → 67번에서 저장한 Few-shot 결과
#    → 두 방법의 성능 비교 결과 저장 경로
# ==================================================

# ----------------------------------------------
# ②-1. One-shot 검사 결과 CSV
# ----------------------------------------------
ONE_PATH = Path(
    "reports/day08_one_shot_results.csv"
)

# ----------------------------------------------
# ②-2. Few-shot 검사 결과 CSV
# ----------------------------------------------
FEW_PATH = Path(
    "reports/day08_fewshot_results.csv"
)

# ----------------------------------------------
# ②-3. 성능 비교 결과 CSV
# ----------------------------------------------
OUTPUT_PATH = Path(
    "reports/day08_method_comparison.csv"
)


# ==================================================
# ③ One-shot / Few-shot 검사 결과 불러오기
#
#    → pandas로 두 CSV 파일을 읽습니다.
#
#    각 CSV에는 다음과 같은 내용이 있습니다.
#    sample_id : 검사한 이미지 식별자
#    actual    : 실제 정답
#    predicted : 검사기의 판정 결과
#
#    두 방법에서 공통으로 사용할 항목입니다.
# ==================================================

# ----------------------------------------------
# ③-1. One-shot 결과 불러오기
# ----------------------------------------------
one = pd.read_csv(
    ONE_PATH
)

# ----------------------------------------------
# ③-2. Few-shot 결과 불러오기
# ----------------------------------------------
few = pd.read_csv(
    FEW_PATH
)


# ==================================================
# ④ 같은 Common Query를 사용했는지 확인
#
#    → sample_id를 비교합니다.
#
#    One-shot과 Few-shot은 동일한 평가 이미지로
#    검사했을 때 성능을 공정하게 비교할 수 있습니다.
#
#    이미지 목록이 다르면 프로그램을 중단합니다.
# ==================================================
if set(one["sample_id"]) != set(few["sample_id"]):

    raise RuntimeError(
        "One-shot과 Few-shot의 Common Query가 서로 다릅니다."
    )


# ==================================================
# ⑤ 성능 평가 함수 작성
#
#    함수: metrics()
#
#    → 실제 정답(actual)과 예측(predicted)을 비교
#    → TP / TN / FP / FN 개수 계산
#    → Accuracy / Precision / Recall 계산
#
#    이번 수업에서는 Anomaly를 Positive로 취급합니다.
# ==================================================
def metrics(df):

    # ----------------------------------------------
    # ⑤-1. 실제 정답과 검사 결과 가져오기
    # ----------------------------------------------
    actual = df["actual"]
    predicted = df["predicted"]

    # ----------------------------------------------
    # ⑤-2. TP (True Positive)
    #
    #       실제 이상 → 이상으로 정확히 판정
    # ----------------------------------------------
    tp = int(
        (
            (actual == "Anomaly")
            & (predicted == "Anomaly")
        ).sum()
    )

    # ----------------------------------------------
    # ⑤-3. TN (True Negative)
    #
    #       실제 정상 → 정상으로 정확히 판정
    # ----------------------------------------------
    tn = int(
        (
            (actual == "Normal")
            & (predicted == "Normal")
        ).sum()
    )

    # ----------------------------------------------
    # ⑤-4. FP (False Positive)
    #
    #       실제 정상 → 이상으로 잘못 판정
    #       → 정상 제품 오탐
    # ----------------------------------------------
    fp = int(
        (
            (actual == "Normal")
            & (predicted == "Anomaly")
        ).sum()
    )

    # ----------------------------------------------
    # ⑤-5. FN (False Negative)
    #
    #       실제 이상 → 정상으로 잘못 판정
    #       → 불량 제품 미검출
    # ----------------------------------------------
    fn = int(
        (
            (actual == "Anomaly")
            & (predicted == "Normal")
        ).sum()
    )

    # ----------------------------------------------
    # ⑤-6. 전체 검사 이미지 개수 계산
    #
    #       TP + TN : 정확하게 판정한 이미지
    #       FP + FN : 잘못 판정한 이미지
    # ----------------------------------------------
    total = (
        tp
        + tn
        + fp
        + fn
    )

    # ----------------------------------------------
    # ⑤-7. Accuracy (정확도)
    #
    #       전체 이미지 중 정확히 판정한 비율
    #
    #       (TP + TN) / 전체 이미지
    # ----------------------------------------------
    accuracy = (
        (tp + tn) / total
        if total
        else 0.0
    )

    # ----------------------------------------------
    # ⑤-8. Precision (정밀도)
    #
    #       이상이라고 판정한 이미지 중
    #       실제 이상인 이미지의 비율
    #
    #       TP / (TP + FP)
    # ----------------------------------------------
    precision = (
        tp / (tp + fp)
        if (tp + fp)
        else 0.0
    )

    # ----------------------------------------------
    # ⑤-9. Recall (재현율)
    #
    #       실제 불량 이미지 중
    #       이상으로 찾아낸 이미지의 비율
    #
    #       TP / (TP + FN)
    # ----------------------------------------------
    recall = (
        tp / (tp + fn)
        if (tp + fn)
        else 0.0
    )

    # ----------------------------------------------
    # ⑤-10. 계산한 성능 지표 반환
    #
    #       이후 One-shot과 Few-shot에서
    #       같은 함수를 사용합니다.
    # ----------------------------------------------
    return {
        "samples": total,
        "accuracy": accuracy,
        "anomaly_precision": precision,
        "anomaly_recall": recall,
        "tp": tp,
        "tn": tn,
        "fp": fp,
        "fn": fn,
    }


# ==================================================
# ⑥ 두 방법의 성능을 각각 계산
#
#    → One-shot 결과를 metrics()에 전달
#    → Few-shot 결과를 metrics()에 전달
#    → 같은 평가 지표로 두 방법을 분석
#
#    결과는 rows 리스트에 저장합니다.
# ==================================================

# ----------------------------------------------
# ⑥-1. 비교 결과를 저장할 빈 리스트
# ----------------------------------------------
rows = []

# ----------------------------------------------
# ⑥-2. One-shot / Few-shot 순서대로 평가
# ----------------------------------------------
for method, df in [
    ("one_shot", one),
    ("few_shot", few),
]:

    # ------------------------------------------
    # ⑥-3. 현재 방법의 성능 지표 계산
    # ------------------------------------------
    result = metrics(
        df
    )

    # ------------------------------------------
    # ⑥-4. 검사 방법 이름 추가
    #
    #       one_shot 또는 few_shot
    # ------------------------------------------
    result["method"] = method

    # ------------------------------------------
    # ⑥-5. 계산 결과를 리스트에 저장
    # ------------------------------------------
    rows.append(
        result
    )


# ==================================================
# ⑦ 비교 결과 CSV 컬럼 설정
#
#    → 검사 방법과 이미지 개수
#    → 정확도 / 정밀도 / 재현율
#    → TP / TN / FP / FN 개수
#
#    두 방법의 차이를 한 표에서 확인할 수 있습니다.
# ==================================================
fieldnames = [
    "method",
    "samples",
    "accuracy",
    "anomaly_precision",
    "anomaly_recall",
    "tp",
    "tn",
    "fp",
    "fn",
]


# ==================================================
# ⑧ 성능 비교 결과 CSV 저장
#
#    → reports 폴더 생성
#    → CSV 컬럼명 작성
#    → 각 방법의 성능 지표 저장
#
#    비율은 소수점 4자리로 반올림하여 저장합니다.
# ==================================================

# ----------------------------------------------
# ⑧-1. reports 폴더가 없으면 생성
# ----------------------------------------------
OUTPUT_PATH.parent.mkdir(
    parents=True,
    exist_ok=True
)

# ----------------------------------------------
# ⑧-2. 비교 결과 CSV 열기
# ----------------------------------------------
with OUTPUT_PATH.open(
    "w",
    newline="",
    encoding="utf-8-sig",
) as file:

    # ------------------------------------------
    # ⑧-3. CSV 작성 도구 준비
    # ------------------------------------------
    writer = csv.DictWriter(
        file,
        fieldnames=fieldnames,
    )

    # ------------------------------------------
    # ⑧-4. CSV 컬럼명 작성
    # ------------------------------------------
    writer.writeheader()

    # ------------------------------------------
    # ⑧-5. One-shot / Few-shot 결과 반복
    # ------------------------------------------
    for row in rows:

        # 원본 계산 결과를 복사
        output = dict(row)

        # --------------------------------------
        # ⑧-6. 성능 지표를 소수점 4자리로 반올림
        # --------------------------------------
        output["accuracy"] = round(
            output["accuracy"],
            4
        )

        output["anomaly_precision"] = round(
            output["anomaly_precision"],
            4
        )

        output["anomaly_recall"] = round(
            output["anomaly_recall"],
            4
        )

        # --------------------------------------
        # ⑧-7. 현재 방법의 결과를 CSV에 기록
        # --------------------------------------
        writer.writerow(
            output
        )


# ==================================================
# ⑨ 실행 결과 출력
#
#    → 검사한 전체 이미지 수 출력
#    → Accuracy / Precision / Recall 출력
#    → TP / TN / FP / FN 출력
#    → 결과 CSV 저장 경로 출력
#
#    실제 비교 결과를 확인하고
#    다음 실습에서 성능 차이를 해석합니다.
# ==================================================

# ----------------------------------------------
# ⑨-1. 비교 결과 제목 출력
# ----------------------------------------------
print("=" * 70)
print("DAY08 METHOD COMPARISON")
print("=" * 70)


# ----------------------------------------------
# ⑨-2. One-shot / Few-shot 결과 각각 출력
# ----------------------------------------------
for row in rows:

    print()

    # 현재 검사 방법
    print(
        "Method            :",
        row["method"]
    )

    # 검사 이미지 수
    print(
        "Samples           :",
        row["samples"]
    )

    # 전체 정확도
    print(
        "Accuracy          :",
        f"{row['accuracy']:.4f}"
    )

    # 이상 검출 정밀도
    print(
        "Anomaly Precision :",
        f"{row['anomaly_precision']:.4f}"
    )

    # 이상 검출 재현율
    print(
        "Anomaly Recall    :",
        f"{row['anomaly_recall']:.4f}"
    )

    # TP / TN / FP / FN 개수
    print(
        "TP / TN / FP / FN :",
        row["tp"],
        row["tn"],
        row["fp"],
        row["fn"]
    )


# ----------------------------------------------
# ⑨-3. 결과 파일 저장 위치 출력
# ----------------------------------------------
print()

print(
    "Saved:",
    OUTPUT_PATH
)