# ⑧ 공통 함수 모듈 작성 완료
#
#    이 파일에는 다음 세 가지 주요 함수가 있습니다.
#
#    create_feature_model()
#    → 특징 추출용 ResNet18 준비
#
#    extract_feature()
#    → 이미지 1장의 512차원 특징 추출
#
#    cosine_similarity()
#    → 두 특징의 유사도 계산
#
#    build_prototype()
#    → 여러 Support 특징의 대표값 생성
