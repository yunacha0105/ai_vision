
# ==================================================
# ① 필요한 라이브러리 불러오기
#    → shutil : FP/FN 이미지 복사 및 폴더 초기화
#    → Path   : 파일과 폴더 경로 관리
#    → Pandas : Test 결과 분석 및 통계 계산
# ==================================================
import shutil
from pathlib import Path

import pandas as pd


# ==================================================
# ② 입력 및 출력 경로 설정
#    → 입력 : 56번에서 저장한 Test 검사 결과
#    → 출력 : 성능 평가 Report
#    → FP/FN 이미지를 저장할 폴더 준비
# ==================================================

# 56번에서 생성한 Test 결과 CSV
INPUT_CSV = Path(
    "reports/day07_anomaly_scores.csv"
)

# 성능 평가 결과를 저장할 Markdown 파일
REPORT_PATH = Path(
    "reports/day07_test_metrics.md"
)

# FP: 정상인데 이상으로 잘못 판정한 이미지
FP_DIR = Path(
    "outputs/day07/fp"
)

# FN: 이상인데 정상으로 잘못 판정한 이미지
FN_DIR = Path(
    "outputs/day07/fn"
)


# ==================================================
# ③ 0으로 나누는 오류 방지 함수
#    → Accuracy / Precision / Recall 계산에 사용
#    → 분모가 0이면 0.0 반환
# ==================================================
def safe_divide(a, b):

    return a / b if b else 0.0


# ==================================================
# ④ Test 결과 CSV 불러오기
#    → 56번에서 검사한 이미지 83장 결과 읽기
#    → 파일이 없거나 비어 있으면 오류 발생
# ==================================================

# ----------------------------------------------
# ④-1. Test 결과 CSV 존재 여부 확인
# ----------------------------------------------
if not INPUT_CSV.exists():
    raise FileNotFoundError(
        f"Test 결과 CSV를 확인하세요: {INPUT_CSV}"
    )


# ----------------------------------------------
# ④-2. CSV 파일을 Pandas로 읽기
# ----------------------------------------------
df = pd.read_csv(
    INPUT_CSV
)


# ----------------------------------------------
# ④-3. 검사 결과가 비어 있는지 확인
# ----------------------------------------------
if df.empty:
    raise RuntimeError(
        "Test 결과가 없습니다."
    )


# ==================================================
# ⑤ TP / TN / FP / FN 개수 계산
#    → 56번에서 기록한 error_type 컬럼 사용
#
#    TP : 이상을 이상으로 정확하게 판정
#    TN : 정상을 정상으로 정확하게 판정
#    FP : 정상인데 이상으로 잘못 판정
#    FN : 이상인데 정상으로 잘못 판정
# ==================================================

# ----------------------------------------------
# ⑤-1. error_type별 이미지 개수 계산
# ----------------------------------------------
counts = (
    df["error_type"]
    .value_counts()
    .to_dict()
)


# ----------------------------------------------
# ⑤-2. TP 개수
# ----------------------------------------------
tp = int(
    counts.get("TP", 0)
)


# ----------------------------------------------
# ⑤-3. TN 개수
# ----------------------------------------------
tn = int(
    counts.get("TN", 0)
)


# ----------------------------------------------
# ⑤-4. FP 개수
# ----------------------------------------------
fp = int(
    counts.get("FP", 0)
)


# ----------------------------------------------
# ⑤-5. FN 개수
# ----------------------------------------------
fn = int(
    counts.get("FN", 0)
)


# ----------------------------------------------
# ⑤-6. 전체 검사 이미지 개수
# ----------------------------------------------
total = (
    tp
    + tn
    + fp
    + fn
)


# ==================================================
# ⑥ 성능 평가 지표 계산
#    → Accuracy  : 전체 이미지 중 맞게 판정한 비율
#    → Precision : 이상이라고 판정한 것 중 실제 이상 비율
#    → Recall    : 실제 이상 중 찾아낸 비율
#
#    이번 수업에서는 Anomaly를 Positive로 사용
# ==================================================

# ----------------------------------------------
# ⑥-1. Accuracy (정확도)
#
#       (TP + TN) / 전체 이미지
# ----------------------------------------------
accuracy = safe_divide(
    tp + tn,
    total,
)


# ----------------------------------------------
# ⑥-2. Precision (정밀도)
#
#       TP / (TP + FP)
# ----------------------------------------------
precision = safe_divide(
    tp,
    tp + fp,
)


# ----------------------------------------------
# ⑥-3. Recall (재현율)
#
#       TP / (TP + FN)
# ----------------------------------------------
recall = safe_divide(
    tp,
    tp + fn,
)


# ==================================================
# ⑦ FP / FN 이미지 저장 폴더 준비
#    → 이전 결과 폴더를 초기화
#    → 이번 Test에서 잘못 판정한 이미지 저장 준비
#
#    주의!
#    기존 fp / fn 폴더는 삭제 후 다시 생성됩니다.
# ==================================================
for directory in [
    FP_DIR,
    FN_DIR,
]:

    # 이전 검사 결과 폴더가 있으면 삭제
    if directory.exists():
        shutil.rmtree(
            directory
        )

    # FP / FN 폴더 생성
    directory.mkdir(
        parents=True,
        exist_ok=True,
    )


# ==================================================
# ⑧ FP / FN 이미지 별도로 복사
#    → 잘못 판정한 이미지를 직접 확인하기 위한 작업
#
#    FP : 정상인데 이상으로 판정한 이미지
#    FN : 이상인데 정상으로 판정한 이미지
# ==================================================

# ----------------------------------------------
# ⑧-1. Test 결과 CSV를 한 행씩 확인
# ----------------------------------------------
for _, row in df.iterrows():

    # 검사한 원본 이미지 경로
    source = Path(
        row["file"]
    )

    # 이미지 파일이 없다면 건너뛰기
    if not source.exists():
        continue

    # ------------------------------------------
    # ⑧-2. FP 이미지를 fp 폴더에 복사
    # ------------------------------------------
    if row["error_type"] == "FP":

        shutil.copy2(
            source,
            FP_DIR / source.name,
        )

    # ------------------------------------------
    # ⑧-3. FN 이미지를 fn 폴더에 복사
    #
    #       결함 종류를 파일명 앞에 추가
    #       예: broken_small_000.png
    # ------------------------------------------
    elif row["error_type"] == "FN":

        defect_type = row[
            "defect_type"
        ]

        destination = (
            FN_DIR
            / f"{defect_type}_{source.name}"
        )

        shutil.copy2(
            source,
            destination,
        )


# ==================================================
# ⑨ 이미지 종류별 정확도 계산
#    → good / broken_large / broken_small / contamination
#    → 각 종류에서 얼마나 정확하게 판정했는지 확인
#
#    correct 컬럼:
#    True  = 판정 성공
#    False = 판정 실패
# ==================================================
per_type = (
    df.groupby(
        "defect_type"
    )["correct"]
    .mean()
    .sort_index()
)


# ==================================================
# ⑩ 성능 평가 Report 작성 및 결과 출력
#    → Confusion Matrix 작성
#    → Accuracy / Precision / Recall 기록
#    → 결함 종류별 정확도 기록
#    → Markdown 파일로 저장
# ==================================================

# ----------------------------------------------
# ⑩-1. 평가 Report 내용 준비
# ----------------------------------------------
report_lines = [
    "# Day07 Test Metrics",
    "",
    "## Confusion Matrix",
    "",
    "| Actual / Predicted | Anomaly | Normal |",
    "|---|---:|---:|",
    f"| Anomaly | TP = {tp} | FN = {fn} |",
    f"| Normal | FP = {fp} | TN = {tn} |",
    "",
    "## Metrics",
    "",
    f"- Accuracy: {accuracy:.4f}",
    f"- Anomaly Precision: {precision:.4f}",
    f"- Anomaly Recall: {recall:.4f}",
    f"- FP: {fp}",
    f"- FN: {fn}",
    "",
    "## Type Accuracy",
    "",
]


# ----------------------------------------------
# ⑩-2. 이미지 종류별 정확도 추가
# ----------------------------------------------
for defect_type, value in per_type.items():

    report_lines.append(
        f"- {defect_type}: {value:.4f}"
    )


# ----------------------------------------------
# ⑩-3. Report 저장 폴더 생성
# ----------------------------------------------
REPORT_PATH.parent.mkdir(
    parents=True,
    exist_ok=True,
)


# ----------------------------------------------
# ⑩-4. Markdown Report 파일 저장
# ----------------------------------------------
REPORT_PATH.write_text(
    "\n".join(
        report_lines
    ),
    encoding="utf-8",
)


# ----------------------------------------------
# ⑩-5. 성능 평가 결과 출력
# ----------------------------------------------
print("=" * 70)
print("DAY07 TEST EVALUATION")
print("=" * 70)

print(
    "Total    :",
    total,
)

print(
    "TP       :",
    tp,
)

print(
    "TN       :",
    tn,
)

print(
    "FP       :",
    fp,
)

print(
    "FN       :",
    fn,
)

print(
    "Accuracy :",
    round(
        accuracy,
        4,
    ),
)

print(
    "Precision:",
    round(
        precision,
        4,
    ),
)

print(
    "Recall   :",
    round(
        recall,
        4,
    ),
)

print()

# 이미지 종류별 정확도 출력
print(
    per_type
)

print()

# 평가 Report 저장 위치 출력
print(
    "Report:",
    REPORT_PATH,
)