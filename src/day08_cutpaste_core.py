
# ==================================================
# ① 필요한 라이브러리 불러오기
#
#    → csv    : 합성 과정의 Metadata를 CSV로 저장
#    → random : 이미지, 합성 위치, 크기, 각도 무작위 선택
#    → Path   : 파일과 폴더 경로 관리
#    → cv2    : 이미지 읽기, 결함 추출, 회전, 합성
#    → NumPy  : Mask와 픽셀값 계산
# ==================================================
import csv
import random
from pathlib import Path

import cv2
import numpy as np


# ==================================================
# ② extract_patch() — 실제 결함 영역 추출
#
#    입력:
#    → image_path : 작은 파손이 있는 실제 이미지
#    → mask_path  : 해당 이미지의 Ground Truth Mask
#
#    처리:
#    → 불량 이미지와 Mask 읽기
#    → Mask의 흰색 결함 영역 찾기
#    → 결함을 포함하는 사각형 영역 계산
#    → 결함 Patch와 Patch Mask 추출
#
#    반환:
#    → patch      : 결함이 포함된 이미지 조각
#    → patch_mask : 같은 영역의 결함 위치 Mask
# ==================================================
def extract_patch(image_path, mask_path):

    # ----------------------------------------------
    # ②-1. 실제 불량 이미지 읽기
    #
    #       예: broken_small 이미지 1장
    # ----------------------------------------------
    image = cv2.imread(
        str(image_path)
    )

    # ----------------------------------------------
    # ②-2. 해당 이미지의 Ground Truth Mask 읽기
    #
    #       IMREAD_GRAYSCALE
    #       → Mask를 흑백 이미지로 읽습니다.
    # ----------------------------------------------
    mask = cv2.imread(
        str(mask_path),
        cv2.IMREAD_GRAYSCALE
    )

    # ----------------------------------------------
    # ②-3. 이미지와 Mask가 정상적으로 열렸는지 확인
    # ----------------------------------------------
    if image is None:
        raise FileNotFoundError(
            image_path
        )

    if mask is None:
        raise FileNotFoundError(
            mask_path
        )

    # ----------------------------------------------
    # ②-4. Mask를 흑백 2진 이미지로 변환
    #
    #       Mask 값 > 0 → 255 (흰색, 결함)
    #       나머지      → 0   (검은색, 배경)
    #
    #       binary에는 결함 위치가 표시됩니다.
    # ----------------------------------------------
    binary = np.where(
        mask > 0,
        255,
        0
    ).astype(np.uint8)

    # ----------------------------------------------
    # ②-5. Mask에서 흰색 픽셀 위치 찾기
    #
    #       findNonZero()
    #       → 값이 0이 아닌 픽셀의 좌표를 찾습니다.
    # ----------------------------------------------
    points = cv2.findNonZero(
        binary
    )

    # ----------------------------------------------
    # ②-6. 결함 영역이 없는 Mask인지 확인
    # ----------------------------------------------
    if points is None:
        raise RuntimeError(
            f"Mask가 비어 있습니다: {mask_path}"
        )

    # ----------------------------------------------
    # ②-7. 결함 전체를 포함하는 사각형 계산
    #
    #       x, y : 사각형의 시작 위치
    #       w    : 사각형의 너비
    #       h    : 사각형의 높이
    #
    #       여러 흰색 픽셀이 있는 영역을
    #       하나의 Bounding Rectangle로 묶습니다.
    # ----------------------------------------------
    x, y, w, h = cv2.boundingRect(
        points
    )

    # ----------------------------------------------
    # ②-8. 불량 이미지에서 해당 사각형 잘라내기
    #
    #       이 Patch에는 결함뿐 아니라
    #       주변 픽셀도 포함될 수 있습니다.
    # ----------------------------------------------
    patch = image[
        y:y + h,
        x:x + w
    ].copy()

    # ----------------------------------------------
    # ②-9. 같은 위치의 결함 Mask 잘라내기
    #
    #       이후 합성할 때 흰색 영역만
    #       붙이는 데 사용합니다.
    # ----------------------------------------------
    patch_mask = binary[
        y:y + h,
        x:x + w
    ].copy()

    # ----------------------------------------------
    # ②-10. 추출한 Patch와 Mask 반환
    # ----------------------------------------------
    return patch, patch_mask


# ==================================================
# ③ rotate_pair() — 결함 Patch와 Mask 함께 회전
#
#    입력:
#    → patch : 결함 이미지 조각
#    → mask  : 결함 위치 Mask
#    → angle : 회전 각도
#
#    중요한 점:
#    결함 이미지와 Mask를 같은 각도로 회전해야
#    Mask의 흰 영역이 실제 결함 위치와 일치합니다.
# ==================================================
def rotate_pair(patch, mask, angle):

    # ----------------------------------------------
    # ③-1. Patch의 높이와 너비 확인
    # ----------------------------------------------
    height, width = patch.shape[:2]

    # ----------------------------------------------
    # ③-2. Patch의 중심점을 회전 중심으로 설정
    # ----------------------------------------------
    center = (
        width / 2.0,
        height / 2.0
    )

    # ----------------------------------------------
    # ③-3. 회전 변환 행렬 생성
    #
    #       angle : 회전 각도
    #       1.0   : 크기를 유지하는 배율
    # ----------------------------------------------
    matrix = cv2.getRotationMatrix2D(
        center,
        angle,
        1.0,
    )

    # ----------------------------------------------
    # ③-4. 결함 Patch 회전
    #
    #       INTER_LINEAR : 이미지 픽셀 보간
    #       BORDER_REFLECT: 경계 픽셀 반사 처리
    #
    #       출력 크기는 원래 Patch 크기를 유지
    # ----------------------------------------------
    rotated_patch = cv2.warpAffine(
        patch,
        matrix,
        (width, height),
        flags=cv2.INTER_LINEAR,
        borderMode=cv2.BORDER_REFLECT,
    )

    # ----------------------------------------------
    # ③-5. Mask도 같은 각도로 회전
    #
    #       INTER_NEAREST
    #       → Mask의 결함 영역을 처리할 때 사용
    #
    #       borderValue=0
    #       → 회전 후 빈 영역은 검은색 처리
    # ----------------------------------------------
    rotated_mask = cv2.warpAffine(
        mask,
        matrix,
        (width, height),
        flags=cv2.INTER_NEAREST,
        borderValue=0,
    )

    # ----------------------------------------------
    # ③-6. 회전한 Patch와 Mask 반환
    # ----------------------------------------------
    return rotated_patch, rotated_mask


# ==================================================
# ④ paste_patch() — 정상 이미지에 결함 합성
#
#    입력:
#    → background  : 정상 병 이미지
#    → patch       : 실제 결함 Patch
#    → mask        : 결함 위치 Mask
#    → rng         : 무작위 숫자 생성기
#    → scale_range : 결함 크기 변경 범위
#    → angle_range : 결함 회전 각도 범위
#
#    처리:
#    → Patch 크기와 회전 각도 변경
#    → 정상 병 이미지에서 붙일 위치 결정
#    → Mask를 이용해 결함만 합성
#
#    반환:
#    → result : 합성한 이미지
#    → info   : 결함 위치·크기·각도 등의 정보
# ==================================================
def paste_patch(
    background,
    patch,
    mask,
    rng,
    scale_range=(0.7, 1.2),
    angle_range=(-15.0, 15.0),
):

    # ----------------------------------------------
    # ④-1. 정상 이미지 복사
    #
    #       원본 background를 직접 수정하지 않고
    #       복사본에 결함을 합성합니다.
    # ----------------------------------------------
    result = background.copy()

    # ----------------------------------------------
    # ④-2. 결함의 크기 배율과 회전 각도 선택
    #
    #       scale: 0.7 ~ 1.2
    #       angle: -15도 ~ +15도
    #
    #       범위 안에서 무작위로 선택합니다.
    # ----------------------------------------------
    scale = rng.uniform(
        *scale_range
    )

    angle = rng.uniform(
        *angle_range
    )

    # ----------------------------------------------
    # ④-3. 변경할 Patch 너비와 높이 계산
    #
    #       최소 크기는 4픽셀로 제한합니다.
    # ----------------------------------------------
    new_width = max(
        4,
        int(patch.shape[1] * scale)
    )

    new_height = max(
        4,
        int(patch.shape[0] * scale)
    )

    # ----------------------------------------------
    # ④-4. Patch 크기 변경
    #
    #       INTER_LINEAR로 이미지 크기 조절
    # ----------------------------------------------
    patch = cv2.resize(
        patch,
        (new_width, new_height),
        interpolation=cv2.INTER_LINEAR,
    )

    # ----------------------------------------------
    # ④-5. Mask도 같은 크기로 변경
    #
    #       Patch와 Mask 크기가 같아야 합니다.
    # ----------------------------------------------
    mask = cv2.resize(
        mask,
        (new_width, new_height),
        interpolation=cv2.INTER_NEAREST,
    )

    # ----------------------------------------------
    # ④-6. 결함 Patch와 Mask 함께 회전
    #
    #       앞에서 만든 rotate_pair() 호출
    # ----------------------------------------------
    patch, mask = rotate_pair(
        patch,
        mask,
        angle,
    )

    # ----------------------------------------------
    # ④-7. 정상 이미지와 Patch의 크기 확인
    # ----------------------------------------------
    image_h, image_w = result.shape[:2]
    patch_h, patch_w = patch.shape[:2]

    # ----------------------------------------------
    # ④-8. Patch가 정상 이미지보다 크면 중단
    # ----------------------------------------------
    if patch_w >= image_w or patch_h >= image_h:
        raise RuntimeError(
            "Defect Patch가 정상 이미지보다 큽니다."
        )

    # ----------------------------------------------
    # ④-9. 결함을 붙일 X축 범위 설정
    #
    #       MVTec bottle은 제품이 중앙에 있으므로
    #       교육용 Baseline에서는 중앙 영역 우선
    #
    #       x_min : 이미지 너비의 25% 위치
    #       x_max : 이미지 너비의 75%에서
    #               Patch 너비를 뺀 위치
    # ----------------------------------------------
    x_min = int(image_w * 0.25)

    x_max = (
        int(image_w * 0.75)
        - patch_w
    )

    # ----------------------------------------------
    # ④-10. 결함을 붙일 Y축 범위 설정
    #
    #        이미지 높이의 10% ~ 90% 영역 우선
    # ----------------------------------------------
    y_min = int(image_h * 0.10)

    y_max = (
        int(image_h * 0.90)
        - patch_h
    )

    # ----------------------------------------------
    # ④-11. 중앙 영역에 넣기 어려우면
    #        전체 이미지 범위로 조정
    # ----------------------------------------------
    if x_max <= x_min:
        x_min = 0
        x_max = image_w - patch_w

    if y_max <= y_min:
        y_min = 0
        y_max = image_h - patch_h

    # ----------------------------------------------
    # ④-12. 결함을 붙일 실제 위치 무작위 선택
    #
    #        x, y는 Patch의 왼쪽 위 좌표입니다.
    # ----------------------------------------------
    x = rng.randint(
        x_min,
        x_max
    )

    y = rng.randint(
        y_min,
        y_max
    )

    # ----------------------------------------------
    # ④-13. 정상 이미지에서 합성 위치 잘라내기
    #
    #        ROI = Region Of Interest
    #        → 결함이 붙을 이미지 영역
    # ----------------------------------------------
    roi = result[
        y:y + patch_h,
        x:x + patch_w,
    ]

    # ----------------------------------------------
    # ④-14. Mask를 Alpha 값으로 변환
    #
    #        255 (흰색) → 1.0 : 결함 픽셀
    #          0 (검정) → 0.0 : 정상 픽셀 유지
    # ----------------------------------------------
    alpha = (
        mask.astype(np.float32)
        / 255.0
    )

    # ----------------------------------------------
    # ④-15. 경계가 너무 날카롭지 않도록 Blur
    #
    #        GaussianBlur로 결함 경계의
    #        Alpha 값을 부드럽게 만듭니다.
    # ----------------------------------------------
    alpha = cv2.GaussianBlur(
        alpha,
        (3, 3),
        0
    )

    # ----------------------------------------------
    # ④-16. 컬러 이미지 계산용 차원 추가
    #
    #        (높이, 너비)
    #              ↓
    #        (높이, 너비, 1)
    # ----------------------------------------------
    alpha = alpha[..., None]

    # ----------------------------------------------
    # ④-17. 결함 Patch와 정상 ROI를 합성
    #
    #        alpha가 1에 가까운 곳
    #        → 결함 Patch 비중이 큼
    #
    #        alpha가 0에 가까운 곳
    #        → 정상 이미지 비중이 큼
    # ----------------------------------------------
    blended = (
        patch.astype(np.float32) * alpha
        + roi.astype(np.float32) * (1.0 - alpha)
    )

    # ----------------------------------------------
    # ④-18. 합성 결과를 정상 이미지에 적용
    #
    #        픽셀값을 0~255로 제한한 뒤
    #        uint8 이미지로 변환합니다.
    # ----------------------------------------------
    result[
        y:y + patch_h,
        x:x + patch_w,
    ] = np.clip(
        blended,
        0,
        255
    ).astype(np.uint8)

    # ----------------------------------------------
    # ④-19. 결함 합성 정보 기록
    #
    #        x, y     : 붙인 위치
    #        width    : Patch 너비
    #        height   : Patch 높이
    #        rotation : 회전 각도
    #        scale    : 크기 변경 배율
    # ----------------------------------------------
    info = {
        "x": x,
        "y": y,
        "width": patch_w,
        "height": patch_h,
        "rotation": round(angle, 2),
        "scale": round(scale, 3),
    }

    # ----------------------------------------------
    # ④-20. 합성 이미지와 Metadata 반환
    # ----------------------------------------------
    return result, info


# ==================================================
# ⑤ generate_synthetic_set() — 합성 데이터셋 생성
#
#    앞에서 만든 세 함수를 연결합니다.
#
#    → 정상 이미지와 불량 원본 목록 준비
#    → 이미지들을 무작위로 선택
#    → extract_patch()로 결함 추출
#    → paste_patch()로 정상 이미지에 합성
#    → 합성 이미지 PNG 저장
#    → 생성 정보 Metadata CSV 저장
#
#    이 함수는 뒤의 69번 실행 파일에서 호출합니다.
# ==================================================
def generate_synthetic_set(
    normal_dir,
    defect_image_dir,
    defect_mask_dir,
    output_dir,
    metadata_path,
    defect_type,
    count,
    seed,
    scale_range=(0.7, 1.2),
    angle_range=(-15.0, 15.0),
):

    # ----------------------------------------------
    # ⑤-1. 정상 이미지 목록 불러오기
    #
    #       이번 실습에서는 정상 이미지 10장
    # ----------------------------------------------
    normal_files = sorted(
        Path(normal_dir).glob("*.png")
    )

    # ----------------------------------------------
    # ⑤-2. 결함 원본 이미지 목록 불러오기
    #
    #       이번 실습에서는 broken_small 2장
    # ----------------------------------------------
    defect_files = sorted(
        Path(defect_image_dir).glob("*.png")
    )

    # ----------------------------------------------
    # ⑤-3. 정상 이미지가 존재하는지 확인
    # ----------------------------------------------
    if not normal_files:
        raise RuntimeError(
            "Normal Target 이미지가 없습니다."
        )

    # ----------------------------------------------
    # ⑤-4. 결함 원본이 존재하는지 확인
    # ----------------------------------------------
    if not defect_files:
        raise RuntimeError(
            "Defect Source 이미지가 없습니다."
        )

    # ----------------------------------------------
    # ⑤-5. 출력 경로를 Path 객체로 변환
    # ----------------------------------------------
    output_dir = Path(
        output_dir
    )

    metadata_path = Path(
        metadata_path
    )

    # ----------------------------------------------
    # ⑤-6. 합성 이미지와 Metadata 저장 폴더 생성
    # ----------------------------------------------
    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    metadata_path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    # ----------------------------------------------
    # ⑤-7. 이전 합성 결과 이미지 정리
    #
    #       synthetic_*.png만 삭제합니다.
    #
    #       같은 폴더의 다른 파일은 유지합니다.
    # ----------------------------------------------
    for old_file in output_dir.glob(
        "synthetic_*.png"
    ):
        old_file.unlink()

    # ----------------------------------------------
    # ⑤-8. 고정 Seed로 무작위 선택기 생성
    #
    #       같은 데이터와 설정을 사용하면
    #       같은 선택 순서를 재현할 수 있습니다.
    # ----------------------------------------------
    rng = random.Random(
        seed
    )

    # ----------------------------------------------
    # ⑤-9. Metadata를 저장할 빈 리스트
    # ----------------------------------------------
    rows = []

    # ----------------------------------------------
    # ⑤-10. 요청한 count만큼 합성 반복
    #
    #        예: count=20이면 총 20회 반복
    # ----------------------------------------------
    for index in range(count):

        # ------------------------------------------
        # ⑤-11. 정상 이미지 1장 무작위 선택
        # ------------------------------------------
        normal_path = rng.choice(
            normal_files
        )

        # ------------------------------------------
        # ⑤-12. 결함 원본 1장 무작위 선택
        # ------------------------------------------
        defect_path = rng.choice(
            defect_files
        )

        # ------------------------------------------
        # ⑤-13. 결함 원본과 짝이 되는 Mask 경로
        #
        #        예:
        #        012.png → 012_mask.png
        # ------------------------------------------
        mask_path = (
            Path(defect_mask_dir)
            / f"{defect_path.stem}_mask.png"
        )

        # ------------------------------------------
        # ⑤-14. 정상 바탕 이미지 읽기
        # ------------------------------------------
        background = cv2.imread(
            str(normal_path)
        )

        # ------------------------------------------
        # ⑤-15. 정상 이미지 읽기 실패 확인
        # ------------------------------------------
        if background is None:
            raise FileNotFoundError(
                normal_path
            )

        # ------------------------------------------
        # ⑤-16. extract_patch()로 실제 결함 추출
        #
        #        입력: 불량 원본 + Ground Truth Mask
        #        출력: Patch + Patch Mask
        # ------------------------------------------
        patch, mask = extract_patch(
            defect_path,
            mask_path,
        )

        # ------------------------------------------
        # ⑤-17. paste_patch()로 합성 불량 생성
        #
        #        → 결함 크기·회전 변경
        #        → 붙일 위치 선택
        #        → 정상 이미지에 결함 합성
        #
        #        출력:
        #        synthetic : 합성 이미지
        #        info      : 합성 위치·크기 정보
        # ------------------------------------------
        synthetic, info = paste_patch(
            background,
            patch,
            mask,
            rng,
            scale_range=scale_range,
            angle_range=angle_range,
        )

        # ------------------------------------------
        # ⑤-18. 합성 이미지 파일명 생성
        #
        #        synthetic_000.png
        #        synthetic_001.png
        #        ...
        # ------------------------------------------
        output_name = (
            f"synthetic_{index:03d}.png"
        )

        output_path = (
            output_dir / output_name
        )

        # ------------------------------------------
        # ⑤-19. 합성 이미지를 PNG 파일로 저장
        # ------------------------------------------
        cv2.imwrite(
            str(output_path),
            synthetic
        )

        # ------------------------------------------
        # ⑤-20. 현재 합성 이미지의 Metadata 기록
        #
        #        → 합성 파일명
        #        → 사용한 정상 이미지
        #        → 사용한 결함 원본
        #        → 결함 종류
        #        → Seed
        #        → 위치·크기·회전·배율
        # ------------------------------------------
        rows.append(
            {
                "synthetic_file": output_name,
                "source_normal": normal_path.name,
                "source_defect": defect_path.name,
                "defect_type": defect_type,
                "seed": seed,
                **info,
            }
        )

    # ----------------------------------------------
    # ⑤-21. Metadata CSV 파일 열기
    # ----------------------------------------------
    with metadata_path.open(
        "w",
        newline="",
        encoding="utf-8-sig",
    ) as file:

        # ------------------------------------------
        # ⑤-22. 첫 번째 Metadata의 항목을
        #        CSV 컬럼명으로 사용
        # ------------------------------------------
        writer = csv.DictWriter(
            file,
            fieldnames=rows[0].keys(),
        )

        # ------------------------------------------
        # ⑤-23. CSV 컬럼명 작성
        # ------------------------------------------
        writer.writeheader()

        # ------------------------------------------
        # ⑤-24. 모든 합성 이미지의 Metadata 저장
        # ------------------------------------------
        writer.writerows(
            rows
        )

    # ----------------------------------------------
    # ⑤-25. 생성된 Metadata 목록 반환
    #
    #        호출한 69번 코드에서 결과 확인 가능
    # ----------------------------------------------
    return rows