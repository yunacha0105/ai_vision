from pathlib import Path

import cv2
import numpy as np
import pandas as pd
import torch
import torchvision
import PIL
from PIL import Image


# ==================================================
# ② MVTec bottle 원본 데이터 경로 설정
#    → 7일차에서 사용한 원본 데이터를 재사용
#    → 원본 데이터 자체는 변경하지 않음
#
#    8일차 실습용 데이터는 이후 63번 코드에서
#    필요한 이미지들만 복사하여 준비합니다.
# ==================================================
ROOT = Path(
    "samples/day07/original/bottle"
)


# ==================================================
# ③ 실습에 필요한 원본 폴더 목록 설정
#    → 정상 이미지
#    → 작은 파손 이미지
#    → 오염 이미지
#    → 실제 결함 위치가 표시된 Mask 폴더
#
#    이후 One-shot / Few-shot / 불량 합성
#    실습에 필요한 데이터가 있는지 확인합니다.
# ==================================================
required_dirs = [

    # 정상 학습 이미지
    ROOT / "train/good",

    # 정상 Test 이미지
    ROOT / "test/good",

    # 작은 파손 Test 이미지
    ROOT / "test/broken_small",

    # 오염 Test 이미지
    ROOT / "test/contamination",

    # 작은 파손의 실제 결함 위치 Mask
    ROOT / "ground_truth/broken_small",

    # 오염의 실제 결함 위치 Mask
    ROOT / "ground_truth/contamination",
]


# ==================================================
# ④ AI 실행 환경 확인
#    → 설치된 라이브러리 버전을 출력
#    → CUDA 사용 가능 여부 확인
#    → GPU를 사용할 수 있으면 GPU 이름 출력
#
#    CUDA = False여도 CPU로 실행할 수 있습니다.
#    단, 처리 속도가 느릴 수 있습니다.
# ==================================================

# ----------------------------------------------
# ④-1. 환경 점검 시작 메시지
# ----------------------------------------------
print("=" * 70)
print("DAY08 LOW-DATA ENV CHECK")
print("=" * 70)


# ----------------------------------------------
# ④-2. 라이브러리 버전 확인
# ----------------------------------------------
print("Torch      :", torch.__version__)
print("Torchvision:", torchvision.__version__)
print("OpenCV     :", cv2.__version__)
print("NumPy      :", np.__version__)
print("Pandas     :", pd.__version__)
print("Pillow     :", PIL.__version__)


# ----------------------------------------------
# ④-3. CUDA 사용 가능 여부 확인
# ----------------------------------------------
print(
    "CUDA       :",
    torch.cuda.is_available()
)


# ----------------------------------------------
# ④-4. CUDA 사용이 가능하면 GPU 이름 출력
# ----------------------------------------------
if torch.cuda.is_available():

    print(
        "GPU        :",
        torch.cuda.get_device_name(0)
    )


# ==================================================
# ⑤ 필요한 원본 데이터 폴더 확인
#    → ③에서 지정한 폴더를 하나씩 검사
#    → 존재하면 [OK] 출력
#    → 없으면 FileNotFoundError 발생
#
#    주의!
#    여기서는 폴더가 있는지만 확인합니다.
#    이미지 수량은 다음 단계에서 확인합니다.
# ==================================================
print()

print(
    "Dataset    :",
    ROOT
)


# ----------------------------------------------
# ⑤-1. 필요한 폴더를 하나씩 확인
# ----------------------------------------------
for directory in required_dirs:

    # 폴더가 없으면 오류 발생
    if not directory.exists():

        raise FileNotFoundError(
            directory
        )

    # 경로가 존재하면 확인 메시지 출력
    print(
        "[OK]",
        directory
    )


# ==================================================
# ⑥ 원본 이미지 개수 확인
#    → 정상 Train 이미지 수
#    → 정상 Test 이미지 수
#    → 작은 파손 이미지 수
#    → 오염 이미지 수
#
#    glob("*.png")으로 PNG 이미지를 찾고
#    len()으로 파일 개수를 계산합니다.
# ==================================================

# ----------------------------------------------
# ⑥-1. 이미지 종류별 개수 계산
# ----------------------------------------------
counts = {

    # 정상 Train 이미지
    "train_good": len(
        list(
            (ROOT / "train/good").glob("*.png")
        )
    ),

    # 정상 Test 이미지
    "test_good": len(
        list(
            (ROOT / "test/good").glob("*.png")
        )
    ),

    # 작은 파손 Test 이미지
    "broken_small": len(
        list(
            (ROOT / "test/broken_small").glob("*.png")
        )
    ),

    # 오염 Test 이미지
    "contamination": len(
        list(
            (ROOT / "test/contamination").glob("*.png")
        )
    ),
}


# ----------------------------------------------
# ⑥-2. 이미지 종류별 개수 출력
# ----------------------------------------------
print()

for name, count in counts.items():

    print(
        f"{name:15s}: {count}"
    )


# ==================================================
# ⑦ 실습에 필요한 최소 이미지 수량 검사
#    → 8일차의 데이터 분리 작업에 필요한
#      최소 이미지 개수를 확인
#
#    주의!
#    이것은 모델 학습에 필요한 일반적인
#    최소 이미지 수가 아닙니다.
#
#    이번 8일차 실습을 위한 준비 조건입니다.
# ==================================================

# ----------------------------------------------
# ⑦-1. 종류별 최소 필요 이미지 개수 설정
# ----------------------------------------------
minimum_required = {

    # 정상 원본 Train 이미지
    "train_good": 41,

    # 정상 원본 Test 이미지
    "test_good": 10,

    # 작은 파손 원본 Test 이미지
    "broken_small": 17,

    # 오염 원본 Test 이미지
    "contamination": 2,
}


# ----------------------------------------------
# ⑦-2. 최소 필요 수량과 실제 이미지 수 비교
# ----------------------------------------------
for name, minimum in minimum_required.items():

    # 실제 이미지 수가 부족하면 오류 발생
    if counts[name] < minimum:

        raise RuntimeError(
            f"{name} 이미지가 부족합니다. "
            f"필요: {minimum}, 현재: {counts[name]}"
        )


