# --------------------------------------------------
# 1. OCR 문자열 검사에 필요한 정규식 라이브러리 불러오기
#
# 무엇을 하나요?
# - Python의 re 라이브러리를 불러옵니다.
#
# re:
# Regular Expression(정규식)을 처리하는 라이브러리입니다.
#
# 정규식이란?
# 문자열이 우리가 지정한 형식에 맞는지
# 검사하기 위한 규칙 표현식입니다.
#
# 이번 실습에서 사용할 정규식:
#
# ^[0-9]{13}$
#
# 의미:
# 처음부터 끝까지 숫자만 있고
# 정확히 13자리여야 한다는 뜻입니다.
#
# 왜 필요한가요?
# Tesseract가 읽은 문자열이
# 올바른 SN 형식인지 확인하기 위해서입니다.
# --------------------------------------------------

import re


# --------------------------------------------------
# 2. OCR이 읽은 문자열의 공백과 줄바꿈 정리
#
# 무엇을 하나요?
# - clean_ocr_text() 함수를 정의합니다.
# - OCR이 반환한 문자열을 전달받습니다.
# - 앞뒤 공백과 줄바꿈을 제거합니다.
# - 문자열 중간의 공백도 제거합니다.
#
# raw_text:
# Tesseract가 실제로 반환한 원본 문자열입니다.
#
# 예:
# '0637145699424\n'
#
# raw_text.strip():
# 문자열 앞뒤에 있는 공백과 줄바꿈을 제거합니다.
#
# re.sub(r"\s+", "", text):
# 문자열 안에 있는 공백, 탭, 줄바꿈 등을 제거합니다.
#
# \s:
# 공백, 탭, 줄바꿈과 같은 공백 문자
#
# +:
# 공백 문자가 하나 이상 연속되어 있는 경우
#
# "":
# 찾은 공백을 빈 문자열로 바꿉니다.
#
# 반환 결과:
# 0637145699424
#
# 왜 필요한가요?
# OCR 결과에 불필요한 공백이 포함되어 있으면
# 문자열 길이나 Expected SN 비교에 영향을
# 줄 수 있기 때문입니다.
#
# 주의:
# 이 함수는 공백만 제거하며
# OCR이 읽은 숫자를 다른 숫자로 변경하지 않습니다.
# --------------------------------------------------

def clean_ocr_text(
    raw_text,
):

    # 2-1. 문자열 앞뒤의 공백과 줄바꿈 제거
    #
    # 예:
    # '0637145699424\n'
    #          ↓
    # '0637145699424'

    text = raw_text.strip()


    # 2-2. 문자열 중간의 공백 문자 제거
    #
    # 예:
    # '0637 1456 99424'
    #          ↓
    # '0637145699424'
    #
    # 숫자 자체는 변경하지 않습니다.

    text = re.sub(
        r"\s+",
        "",
        text,
    )


    # 정리된 OCR 문자열 반환
    return text


# --------------------------------------------------
# 3. OCR 문자열이 정해진 SN 형식에 맞는지 검사
#
# 무엇을 하나요?
# - validate_pattern() 함수를 정의합니다.
# - OCR 문자열과 정규식을 전달받습니다.
# - 문자열이 정규식과 완전히 일치하는지 검사합니다.
#
# text:
# 공백과 줄바꿈이 정리된 OCR 문자열
#
# pattern:
# SN 형식을 정의한 정규식
#
# 이번 실습의 정규식:
# ^[0-9]{13}$
#
# ^:
# 문자열 시작
#
# [0-9]:
# 숫자 0~9 중 한 개
#
# {13}:
# 숫자가 정확히 13개
#
# $:
# 문자열 끝
#
# re.fullmatch():
# 문자열 전체가 지정한 정규식에
# 일치하는지 확인하는 함수입니다.
#
# bool():
# 검사 결과를 True 또는 False로 변환합니다.
#
# 예:
#
# 0637145699424
# → True
#
# 063714569942
# → False (12자리)
#
# ABC1234567890
# → False (영문 포함)
#
# 왜 필요한가요?
# Tesseract가 문자를 읽었다고 하더라도
# SN이 정확히 숫자 13자리인지는
# 별도로 확인해야 하기 때문입니다.
#
# 주의:
# 13자리 형식이 맞는 것과
# Expected SN이 일치하는 것은 다른 검사입니다.
# --------------------------------------------------

def validate_pattern(
    text,
    pattern,
):

    return bool(
        re.fullmatch(
            pattern,
            text,
        )
    )


# --------------------------------------------------
# 4. OCR 문자열을 정리하고 최종 검사 준비
#
# 무엇을 하나요?
# - inspect_text() 함수를 정의합니다.
# - OCR 결과와 Expected SN, 정규식을 전달받습니다.
# - clean_ocr_text()를 호출하여 문자열을 정리합니다.
# - 검사 실패 이유를 저장할 리스트를 준비합니다.
#
# raw_text:
# Tesseract가 읽은 원본 문자열
#
# expected_text:
# 해당 제품에 인쇄되어 있어야 하는 SN
#
# pattern:
# OCR 문자열이 만족해야 하는 형식
#
# 예:
# raw_text = '0637145699424\n'
#
# expected_text = '0637145699424'
#
# pattern = r'^[0-9]{13}$'
#
# cleaned_text:
# 공백을 제거한 OCR 문자열
#
# reasons:
# 검사 기준을 만족하지 못한 이유를
# 저장하는 리스트입니다.
#
# 왜 필요한가요?
# OCR 결과에 대해 다음 세 가지를 검사하기 위해서입니다.
#
# ① OCR 결과가 비어 있는가?
# ② 숫자 13자리 형식인가?
# ③ Expected SN과 같은가?
# --------------------------------------------------

def inspect_text(
    raw_text,
    expected_text,
    pattern,
):

    # OCR 문자열 정리 함수 호출
    cleaned_text = (
        clean_ocr_text(
            raw_text
        )
    )

    # 검사 실패 이유를 저장할 빈 리스트
    reasons = []


    # --------------------------------------------------
    # 5. OCR 결과가 비어 있는지 확인
    #
    # 무엇을 하나요?
    # - 정리된 OCR 문자열이 비어 있는지 확인합니다.
    # - 비어 있다면 NG_OCR_EMPTY를 기록합니다.
    #
    # if not cleaned_text:
    # 문자열이 비어 있는지 확인하는 조건입니다.
    #
    # 예:
    # raw_text = '\n'
    #
    # Cleaning 이후:
    # cleaned_text = ''
    #
    # 검사 결과:
    # NG_OCR_EMPTY
    #
    # 왜 필요한가요?
    # Tesseract가 문자를 전혀 읽지 못한 경우와
    # 일부 숫자를 잘못 읽은 경우를
    # 구분하여 기록하기 위해서입니다.
    #
    # 주의:
    # OCR 결과가 비어 있다는 것은
    # OCR이 문자를 인식하지 못했다는 의미입니다.
    #
    # 제품에 실제로 문자가 없는지까지
    # 이 코드만으로 판단할 수는 없습니다.
    # --------------------------------------------------

    if not cleaned_text:
        reasons.append(
            "NG_OCR_EMPTY"
        )


    # --------------------------------------------------
    # 6. OCR 결과가 정확히 숫자 13자리인지 검사
    #
    # 무엇을 하나요?
    # - validate_pattern() 함수를 호출합니다.
    # - cleaned_text가 정규식을 만족하는지 검사합니다.
    # - 형식이 틀리면 NG_FORMAT을 기록합니다.
    #
    # 검사 정규식:
    # ^[0-9]{13}$
    #
    # 예 1:
    # OCR = 0637145699424
    # → 숫자 13자리
    # → format_ok = True
    #
    # 예 2:
    # OCR = 9728
    # → 4자리
    # → format_ok = False
    #
    # 예 3:
    # OCR = 063714569942A
    # → 영문 포함
    # → format_ok = False
    #
    # 왜 필요한가요?
    # 제조 현장에서 사용할 SN은
    # 정해진 문자열 형식을 만족해야 하기 때문입니다.
    #
    # 주의:
    # 숫자 13자리 형식이 맞더라도
    # 실제 Expected SN과 다를 수 있습니다.
    # --------------------------------------------------

    format_ok = (
        validate_pattern(
            cleaned_text,
            pattern,
        )
    )

    if not format_ok:
        reasons.append(
            "NG_FORMAT"
        )


    # --------------------------------------------------
    # 7. OCR 결과와 Expected SN을 정확히 비교
    #
    # 무엇을 하나요?
    # - 정리된 OCR 결과와 Expected SN을 비교합니다.
    # - 두 문자열이 완전히 같은지 확인합니다.
    # - 다르면 NG_EXPECTED_MISMATCH를 기록합니다.
    #
    # cleaned_text:
    # OCR이 읽은 SN
    #
    # expected_text:
    # 생산상 인쇄되어 있어야 하는 SN
    #
    # 예 1:
    #
    # OCR:
    # 0637145699424
    #
    # Expected:
    # 0637145699424
    #
    # 결과:
    # expected_match = True
    #
    # 예 2:
    #
    # OCR:
    # 0679256889404
    #
    # Expected:
    # 0679256889400
    #
    # 결과:
    # expected_match = False
    #
    # NG_EXPECTED_MISMATCH:
    # OCR 결과와 Expected SN이 다르다는 의미입니다.
    #
    # 왜 필요한가요?
    # 13자리 숫자 형식이 정확하더라도
    # 제품에 인쇄되어야 하는 번호와 다르면
    # 정상 제품으로 판정할 수 없기 때문입니다.
    #
    # 주의:
    # OCR 결과가 다르다는 사실만으로
    # 실제 인쇄 오류인지 OCR 인식 오류인지
    # 확정할 수는 없습니다.
    # --------------------------------------------------

    expected_match = (
        cleaned_text
        == expected_text
    )

    if not expected_match:
        reasons.append(
            "NG_EXPECTED_MISMATCH"
        )


    # --------------------------------------------------
    # 8. 검사 실패 이유를 확인하여 최종 OK / NG 판정
    #
    # 무엇을 하나요?
    # - reasons 리스트에 실패 이유가 있는지 확인합니다.
    # - 실패 이유가 없다면 OK로 판정합니다.
    # - 하나라도 있다면 NG로 판정합니다.
    #
    # 최종 판정 조건:
    #
    # OCR 결과가 비어 있지 않음
    #          AND
    # 숫자 13자리 형식 만족
    #          AND
    # Expected SN과 일치
    #
    # 모두 만족하면:
    # predicted_status = OK
    #
    # 하나라도 만족하지 못하면:
    # predicted_status = NG
    #
    # 왜 필요한가요?
    # OCR 결과에 대한 검사 조건을 종합하여
    # 최종 제품 판정을 만들기 위해서입니다.
    #
    # 주의:
    # 이 코드는 앞의 세 조건을 모두 검사하므로
    # 하나의 이미지에서 여러 NG Reason이
    # 동시에 기록될 수 있습니다.
    # --------------------------------------------------

    predicted_status = (
        "OK"
        if not reasons
        else "NG"
    )


    # --------------------------------------------------
    # 9. OCR 검사 결과를 딕셔너리로 반환
    #
    # 무엇을 하나요?
    # - 원본 OCR 문자열을 저장합니다.
    # - 정리된 OCR 문자열을 저장합니다.
    # - 형식 검사 결과를 저장합니다.
    # - Expected SN 비교 결과를 저장합니다.
    # - 최종 OK/NG 판정과 실패 이유를 저장합니다.
    #
    # raw_text:
    # Tesseract가 반환한 원본 문자열
    #
    # cleaned_text:
    # 공백과 줄바꿈을 제거한 문자열
    #
    # final_text:
    # 최종 비교에 사용하는 문자열
    #
    # format_ok:
    # SN 형식 검사 결과(True / False)
    #
    # expected_match:
    # Expected SN과 일치 여부
    #
    # predicted_status:
    # 최종 OK / NG 판정
    #
    # reasons:
    # NG 판정 이유를 저장한 리스트
    #
    # 왜 필요한가요?
    # 이후 Batch 검사에서 같은 결과를
    # CSV에 저장하고 성능을 평가하기 위해서입니다.
    #
    # 이번 실습에서는 문자 자동 교정을 하지 않으므로
    # final_text와 cleaned_text는 동일한 값입니다.
    # --------------------------------------------------

    return {
        "raw_text":
            raw_text,

        "cleaned_text":
            cleaned_text,

        "final_text":
            cleaned_text,

        "format_ok":
            format_ok,

        "expected_match":
            expected_match,

        "predicted_status":
            predicted_status,

        "reasons":
            reasons,
    }